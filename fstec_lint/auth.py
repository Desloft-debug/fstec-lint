"""Виды аутентификации и уровни доверия по ГОСТ Р 58833-2020.

ГОСТ Р 58833-2020 «Защита информации. Идентификация и аутентификация.
Общие требования» (введён приказом Росстандарта от 10.04.2020 N 159-ст,
разработан ФСТЭК России). Приказ ФСТЭК N 117 ссылается на него.

Раздел 7.2 связывает вид аутентификации с уровнем доверия к её
результату; отсюда severity правил об аутентификации.

Не путать с «уровнем доверия» из п. 72 приказа N 117: там это класс
доверия к СЗИ (4, 5, 6), здесь — уверенность в результате
аутентификации (низкий, средний, высокий).
"""

from __future__ import annotations

from dataclasses import dataclass

STANDARD = "ГОСТ Р 58833-2020"


@dataclass(frozen=True)
class AuthenticationKind:
    """Вид аутентификации и уровень доверия, который он обеспечивает."""

    name: str
    clause: str
    method: str
    trust_level: str
    trust_clause: str = "7.2"


# Раздел 3 — определения видов; раздел 7.2 — достигаемый уровень доверия.
KINDS: dict[str, AuthenticationKind] = {
    "простая": AuthenticationKind(
        name="простая аутентификация",
        clause="3.46",
        method="однофакторная односторонняя аутентификация",
        trust_level="низкий",
    ),
    "усиленная": AuthenticationKind(
        name="усиленная аутентификация",
        clause="3.59",
        method="многофакторная односторонняя или взаимная аутентификация",
        trust_level="средний",
    ),
    "строгая": AuthenticationKind(
        name="строгая аутентификация",
        clause="3.54",
        method="многофакторная взаимная аутентификация с криптографическими протоколами",
        trust_level="высокий",
    ),
}

# П. 6.9: вход по паролю — простая аутентификация, низкий уровень доверия.
# Основание для S002, S003, P001.
PASSWORD_AUTH_CLAUSE = "6.9"

# П. 6.18: средство аутентификации не должно входить в объект доступа.
# Основание для C004 и D003 (секрет лежит в защищаемой конфигурации).
AUTH_DEVICE_SEPARATION_CLAUSE = "6.18"


def trust_level(kind: str) -> str | None:
    """Уровень доверия, достигаемый видом аутентификации (раздел 7.2)."""
    entry = KINDS.get(kind)
    return entry.trust_level if entry else None
