# Частные показатели, для которых прогон инструмента даёт подтверждающий
# материал. Пункт 20 и) Методики прямо называет исходными данными
# «результаты работы инструментальных средств оценки (анализа)
# защищённости», а приложение N 1 требует для k32 отчёт средства анализа
# защищённости, для k31 — перечень интерфейсов, доступных из Интернета.
#
# Это материал ДЛЯ оценки, а не сама оценка: значение показателю
# присваивает орган (организация) по совокупности данных.
SUPPORTED_INDICATORS: dict[str, tuple[str, ...]] = {
    "k23": ("C004", "D003", "P001"),
    "k31": ("C005", "C007", "C011", "P002", "P003"),
    "k32": ("C006", "D004"),
    "k42": ("P004", "P007"),
}

# Пороги из таблицы 2 Методики.
LEVELS: tuple[tuple[str, str], ...] = (
    ("Кзи = 1", "минимальный базовый («зелёный»)"),
    ("0,75 < Кзи < 1", "низкий («оранжевый»)"),
    ("Кзи ≤ 0,75", "критический («красный»)"),
)


def indicator(code: str) -> Indicator | None:
    """Частный показатель по коду вида 'k32', None — если такого нет."""
    for group in GROUPS:
        for item in group.indicators:
            if item.code == code:
                return item
    return None
