# Нормированное значение (пункт 9 Методики): система имеет минимальный
# уровень защищённости только при Кзи = 1.
NORMATIVE_VALUE = 1.0


@dataclass(frozen=True)
class Indicator:
    """Частный показатель безопасности k(j,i) из таблицы 1 Методики."""

    group: int
    number: int
    title: str
    value: float

    @property
    def code(self) -> str:
        return f"k{self.group}{self.number}"


@dataclass(frozen=True)
class Group:
    """Группа частных показателей и её весовой коэффициент R(j)."""

    number: int
    title: str
    weight: float
    indicators: tuple[Indicator, ...]


def _group(number: int, title: str, weight: float, rows: list[tuple[int, str, float]]) -> Group:
    return Group(
        number=number,
        title=title,
        weight=weight,
        indicators=tuple(Indicator(number, i, t, v) for i, t, v in rows),
    )


