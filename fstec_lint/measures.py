def submeasure_group(code: str) -> str:
    """'ЗКО.5' -> 'ЗКО'."""
    return code.split(".", 1)[0]


def clause_title(clause: str, letter: str) -> str | None:
    """Наименование подпункта приказа, None — если такого подпункта нет."""
    return CLAUSES.get(clause, {}).get(letter)
