@dataclass(frozen=True)
class Measure:
    """Мера приказа N 21 и уровни защищённости, чей базовый набор её включает."""

    code: str
    title: str
    levels: frozenset[int]

    @property
    def group(self) -> str:
        return self.code.split(".", 1)[0]


def _measure(code: str, title: str, *levels: int) -> Measure:
    return Measure(code=code, title=title, levels=frozenset(levels))


